def register(app, m):
    work_root = Path(os.getenv("COMFY_ROOT", r"D:\ComfyUI-LTX2")) / "input" / "vsa_tools"

    async def _save(up: UploadFile, d: Path, name: str) -> str:
        data = await up.read()
        if not data:
            raise HTTPException(400, f"Empty upload: {name}")
        p = d / name
        p.write_bytes(data)
        return str(p)

    def _transcribe(path: str) -> dict:
        import whisper_stt
        return whisper_stt.transcribe(path)

    @app.post("/api/tools/save_output")
    async def save_output(file: UploadFile = File(...), name: str = Form("video")):
        """Write a finished video to the user's Hoodsfield_Output folder on the Desktop (or $HOODSFIELD_OUTPUT) so it exists as a real file."""
        data = await file.read()
        if not data:
            raise HTTPException(400, "Empty upload")
        base = Path(os.getenv("HOODSFIELD_OUTPUT") or (Path.home() / "OneDrive" / "Desktop" / "Hoodsfield_Output"))
        if not base.parent.exists():
            base = Path.home() / "Desktop" / "Hoodsfield_Output"
        base.mkdir(parents=True, exist_ok=True)
        stem = re.sub(r"[^A-Za-z0-9._ -]+", "_", name).strip() or "video"
        p = base / f"{stem}_{time.strftime('%Y%m%d_%H%M%S')}.mp4"
        p.write_bytes(data)
        return {"path": str(p), "bytes": len(data)}

    @app.post("/api/tools/chaos_analyze")
    async def chaos_analyze(file: UploadFile = File(...)):
        d = work_root / f"chaos_{uuid.uuid4().hex[:8]}"
        d.mkdir(parents=True, exist_ok=True)
        try:
            p = await _save(file, d, "clip.mp4")
            return await asyncio.to_thread(analyze_clip, p, _transcribe)
        finally:
            for f in d.glob("*"):
                f.unlink(missing_ok=True)
            d.rmdir()

    @app.post("/api/tools/chaos_plan")
    async def chaos_plan(body: dict = Body(...)):
        an = body.get("analyses") or []
        if not an:
            raise HTTPException(400, "No clip analyses given")
        return make_plan(an, body.get("opts") or {})

    @app.post("/api/tools/chaos_cut")
    async def chaos_cut(plan: str = Form(...), clips: list[UploadFile] = File(...), beds: list[UploadFile] = File([]), bed_names: str = Form(""),
                        avatar: UploadFile | None = File(None)):
        try:
            pl = json.loads(plan)
        except Exception:
            raise HTTPException(400, "plan must be JSON")
        d = work_root / f"chaoscut_{uuid.uuid4().hex[:8]}"
        d.mkdir(parents=True, exist_ok=True)
        try:
            cps = [await _save(c, d, f"clip{i}.mp4") for i, c in enumerate(clips)]
            names = [x for x in bed_names.split(",") if x]
            bps = {}
            for i, b in enumerate(beds):
                bps[names[i] if i < len(names) else f"bed{i}"] = await _save(b, d, f"bed{i}.mp4")
            if avatar is not None and (avatar.filename or ""):
                try:
                    pl["avatar_path"] = await _save(avatar, d, "avatar.png")
                except HTTPException:
                    pass
            for s in pl.get("segments", []):
                if not (0 <= int(s["clip"]) < len(cps)):
                    raise HTTPException(400, f"Segment refers to clip {s['clip']} but only {len(cps)} were uploaded")
            out = str(d / "out.mp4")
            t0 = time.time()
            try:
                info = await asyncio.to_thread(build, pl, cps, bps, out, d)
            except HTTPException:
                raise
            except Exception as e:
                raise HTTPException(500, f"Chaos cut failed: {str(e)[:400]}")
            data = Path(out).read_bytes()
            return Response(content=data, media_type="video/mp4",
                            headers={"X-Chaos-Seed": str(info["seed"]), "X-Chaos-Score": json.dumps(info["score"]), "X-Chaos-Seconds": str(round(time.time() - t0, 1)),
                                     "X-Chaos-Length": str(info["total"]), "X-Chaos-Notes": "; ".join(info.get("notes", []))[:300].encode("ascii", "replace").decode(),
                                     "Access-Control-Expose-Headers": "X-Chaos-Seed,X-Chaos-Score,X-Chaos-Seconds,X-Chaos-Length,X-Chaos-Notes"})
        finally:
            for f in d.glob("*"):
                try:
                    f.unlink()
                except OSError:
                    pass
            try:
                d.rmdir()
            except OSError:
                pass
