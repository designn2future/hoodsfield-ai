def _run(args: list[str]) -> None:
    r = subprocess.run([ffmpeg_exe(), "-y", "-loglevel", "error", *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(r.stderr[-500:])


# ------------------------------------------------------------------ analysis
def find_glitch_tail(path: str) -> tuple[float | None, float]:
    """Time of a sudden scene change inside a clip (the video model inventing a new scene), or None.
    Frames are compared as tiny thumbnails with brightness removed, so flicker and exposure swings do not count but a different scene does."""
    r = subprocess.run([ffmpeg_exe(), "-v", "error", "-i", path, "-an", "-vf", "fps=12,scale=24:42,format=gray", "-f", "rawvideo", "-"], capture_output=True)
    if not r.stdout:
        return None, 0.0
    a = np.frombuffer(r.stdout, np.uint8).reshape(-1, 42, 24).astype(np.float32) / 255
    if len(a) < 4:
        return None, 0.0
    d = []
    for i in range(1, len(a)):
        x, y = a[i - 1], a[i]
        x = (x - x.mean()) / (x.std() + 0.02)
        y = (y - y.mean()) / (y.std() + 0.02)
        d.append(float(np.abs(x - y).mean()))
    d = np.array(d)
    thr = max(0.30, 3.5 * float(np.median(d)))
    dur = len(a) / 12
    for i, v in enumerate(d):
        # the model invents a new scene near the END of a clip; a big change in the first 40% is the filmed action itself (a whip-pan, a fall), not a glitch
        if v > thr and (i + 1) / 12 >= 0.4 * dur:
            return round((i + 1) / 12, 2), float(v)
    return None, float(d.max())


def mean_db(path: str, dur: float) -> float:
    x = sd.decode_audio(ffmpeg_exe(), path, dur)
    return float(20 * math.log10(np.sqrt((x ** 2).mean()) + 1e-9))


def analyze_clip(path: str, transcribe) -> dict:
    info = sd.probe(ffmpeg_exe(), path)
    dur = info["duration"]
    cut, strength = find_glitch_tail(path)
    speech = []
    if info["audio"]:
        try:
            res = transcribe(path)
            speech = [{"start": float(s["start"]), "end": float(s["end"]), "text": s.get("text", "").strip()} for s in res.get("segments", []) if s.get("text", "").strip()]
        except Exception:
            speech = []
    return {"duration": round(dur, 2), "mean_db": round(mean_db(path, dur), 1) if info["audio"] else -60.0, "glitch_at": cut,
            "safe_end": round((cut - 0.12) if cut else dur - 0.05, 2), "speech": speech, "width": info["width"], "height": info["height"]}


# ------------------------------------------------------------------ planning
def make_plan(analyses: list[dict], opts: dict) -> dict:
    """Clips (in story order) -> trims, chaos, gains and a crowd, tuned so the video accelerates and builds to the last shot."""
    n = len(analyses)
    cam = opts.get("profile") == "cam"
    vlog = opts.get("profile") in ("vlog", "cam")        # quiet and calm; the fixed-camera profile also never shakes"
    pace = {"fast": (2.8, 1.8), "very fast": (2.2, 1.3), "relaxed": (3.6, 2.6)}.get(opts.get("pace", "fast"), (2.8, 1.8))
    climax = float(opts.get("climax_seconds", 3.5))
    segs = []
    for i, an in enumerate(analyses):
        f = i / max(1, n - 1)
        last = i == n - 1
        L = climax if last else pace[0] + (pace[1] - pace[0]) * f
        if (opts.get("beats") or [None] * n)[i] == "payoff" and not last:
            L = max(L, 4.4)        # the event itself (a lamp tipping over, a door opening) plays in full
        safe = max(0.6, float(an.get("safe_end") or an["duration"] - 0.05))
        sp = [s for s in an.get("speech", []) if s["end"] - s["start"] >= 0.25]
        if sp and not last:
            a = max(0.0, sp[0]["start"] - 0.55)
            b = min(safe, max(a + L, sp[-1]["end"] + 0.25))
            b = min(b, a + 4.2)
        else:
            a = 0.0
            b = min(safe, a + L)
        if b - a < 0.8:
            b = min(safe, a + 0.8)
        chaos = 0.0 if cam else ((0.55 if last else 0.3 if i == n - 2 else 0.12) if vlog else 0.15 + 0.85 * (f ** 1.1))
        tgt = -17.0
        gain = max(-14.0, min(6.0, tgt - float(an.get("mean_db", -17))))
        if vlog:      # keep the room sound low (a TikTok track will be added on top); the one event (a crash) stays audible
            gain = -4.0 if (opts.get("beats") or [None] * n)[i] == "payoff" else -12.0
        segs.append({"clip": i, "in": round(a, 2), "out": round(b, 2), "chaos": round(chaos, 2), "gain": round(gain, 1), "audio_clip": None, "audio_in": 0.0})
    total = sum(s["out"] - s["in"] for s in segs)
    amount = opts.get("crowd", "a lot")
    crowd = []
    if amount != "off":
        off = 0.0 if amount == "a lot" else -4.0
        layout = [("calm", 0.01, 4.4, -17), ("uneasy", 0.11, 4.4, -15), ("alarm", 0.24, 4.4, -13), ("alarm2", 0.37, 4.4, -11.5), ("scream", 0.49, 4.4, -10),
                  ("alarm", 0.57, 3.6, -9), ("scream2", 0.65, 4.6, -7), ("scream", 0.73, 3.6, -5.5), ("scream2", 0.78, 4.6, -4)]
        if amount == "some":
            layout = [x for k, x in enumerate(layout) if k % 2 == 0 or k >= 6]
        for mood, fs, ln, g in layout:
            st = fs * total
            L = min(ln, total - st)
            if L > 0.6:
                crowd.append({"bed": mood, "start": round(st, 2), "len": round(L, 2), "gain": round(g + off, 1)})
    return {
        "segments": segs, "crowd": crowd, "total": round(total, 2),
        "look": opts.get("look", "doorbellcam" if cam else "ugc" if vlog else "tiktok"), "shake": opts.get("shake", "none" if cam else "blair witch"), "wear": opts.get("wear", "heavy"), "grain": opts.get("grain", "medium"),
        "focus": opts.get("focus", "off"), "glitches": opts.get("glitches", "none"),
        "ambience": opts.get("ambience", "none" if vlog else "car interior"), "unease": opts.get("unease", "none" if vlog else "low"), "bumps": bool(opts.get("bumps", not vlog)),
        "flaws": opts.get("flaws", "off" if vlog else "a lot"), "ambience_fade": opts.get("ambience_fade"), "cheap_mic": bool(opts.get("cheap_mic", not vlog)),
        "reply_header": opts.get("reply_header", "Reply to a comment"), "scare_at": float(opts.get("scare_at", -1)),
        "ramp": {"from_db": float(opts.get("ramp_from", 4 if not vlog else 3)), "to_db": float(opts.get("ramp_to", 13 if not vlog else 6)), "curve": 1.4},
        "profile": "cam" if cam else "vlog" if vlog else "panic", "voice": opts.get("voice", ""), "exaggeration": float(opts.get("exaggeration", 0.4)),
        "auto_seed": int(opts.get("auto_seed", 4)), "seed": int(opts.get("seed", 11)),
    }


# ------------------------------------------------------------------ building
def _piece(clip: str, has_audio: bool, a: float, b: float, gain: float, fade_tail: bool, W: int, H: int, out: str,
           audio_clip: str | None = None, audio_has: bool = True, audio_in: float = 0.0, lift: list | None = None) -> None:
    d = max(0.3, b - a)
    vf = f"scale={W}:{H}:force_original_aspect_ratio=increase:flags=lanczos,crop={W}:{H},setsar=1,fps=24"
    if fade_tail:
        vf += f",fade=t=out:st={max(0.0, d - 0.12):.2f}:d=0.12"
    af = f"aresample=44100,volume={gain}dB"
    for l0, l1, db in (lift or []):
        af += f",volume={db}dB:enable='between(t,{l0},{l1})'"
    if fade_tail:
        af += f",afade=t=out:st={max(0.0, d - 0.1):.2f}:d=0.1"
    src_a = audio_clip or clip
    src_has = audio_has if audio_clip else has_audio
    args = ["-ss", f"{a:.3f}", "-t", f"{d:.3f}", "-i", clip]
    if audio_clip:
        args += ["-ss", f"{audio_in:.3f}", "-t", f"{d:.3f}", "-i", audio_clip]
        amap = ["-map", "1:a:0"] if src_has else None
    else:
        amap = ["-map", "0:a:0"] if src_has else None
    if amap is None:       # a clip without sound still needs an audio track so every piece joins cleanly
        args += ["-f", "lavfi", "-t", f"{d:.3f}", "-i", "anullsrc=r=44100:cl=stereo"]
        amap = ["-map", f"{2 if audio_clip else 1}:a:0"]
    _run([*args, "-map", "0:v:0", *amap, "-vf", vf, "-af", af, "-ac", "2", "-t", f"{d:.3f}", "-c:v", "libx264", "-crf", "12", "-c:a", "aac", "-b:a", "160k", out])


def _shake_env(segs: list[dict], starts: list[float]) -> str:
    pts = []
    for s, t0 in zip(segs, starts):
        d = s["out"] - s["in"]
        c = float(s.get("chaos", 0.4))
        m = 0.0 if c <= 0.01 else 0.15 + 0.85 * c      # chaos 0 = a locked-off camera: no shake at all
        pts += [f"{t0 + 0.06:.2f}:{m:.3f}", f"{t0 + d - 0.06:.2f}:{m:.3f}"]
    return ",".join(pts)


def _look_pass(src: str, out: str, plan: dict, env: str, seed: int) -> None:
    info = sd.probe(ffmpeg_exe(), src)
    dur = max(0.5, info["duration"])
    lv = lambda table, key, default: table.get(key, table.get(default))
    wear_lv = lv({"light": 0.2, "medium": 0.5, "heavy": 0.9}, plan.get("wear", "heavy"), "medium")
    g = ft.build(plan.get("look", "tiktok"), info["width"] or 480, info["height"] or 832, 24.0, dur,
                 shake=lv(ft.SHAKE_LEVELS, plan.get("shake", "blair witch"), "medium"), focus=lv({"off": 0.0, "some": 0.3, "a lot": 0.75}, plan.get("focus", "off"), "off"),
                 grain=lv({"low": 0.2, "medium": 0.5, "high": 0.9}, plan.get("grain", "medium"), "medium"), wear=wear_lv,
                 glitch=lv({"none": 0.0, "few": 0.35, "many": 0.9}, plan.get("glitches", "none"), "none"), stamp=False, seed=seed, has_audio=info["audio"],
                 audio="passthrough", cam_name="CAM", maxside=1280 if plan.get("quality") == "high" else 960, shake_env=[(float(a), float(b)) for a, b in (p.split(":") for p in env.split(",") if ":" in p)] or None)
    crf = 20 + int(10 * wear_lv)
    rate = []
    if plan.get("look") == "tiktok":
        crf = max(crf, 31)
        rate = ["-maxrate", "380k", "-bufsize", "760k"]
    elif plan.get("look") in ("ugc", "doorbellcam", "babycam", "trailcam"):
        crf = max(crf, 27)
        rate = ["-maxrate", "900k", "-bufsize", "1800k"]
    preset = "veryfast"
    if plan.get("quality") == "high":      # same look, but not starved: the cheap-bitrate crush is what made it look low quality
        crf = min(crf, 20)
        rate = ["-maxrate", "8M", "-bufsize", "16M"]
        preset = "medium"
    _run(["-i", src, "-filter_complex", g["fc"], "-map", g["v"], *(["-map", g["a"], "-c:a", "aac", "-b:a", "96k"] if g["a"] else ["-map", "0:a:0", "-c:a", "aac", "-b:a", "128k"]),
          "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", str(crf), *rate, "-preset", preset, "-movflags", "+faststart", out])


def _sound_pass(look: str, out: str, plan: dict, crowd_files: list[tuple[np.ndarray, float, float]], seed: int, total: float) -> None:
    ff = ffmpeg_exe()
    info = sd.probe(ff, look)
    dur = max(0.5, info["duration"])
    events = sd.motion_events(ff, look, dur) if plan.get("bumps", True) else []
    orig = sd.decode_audio(ff, look, dur)
    fade = plan.get("ambience_fade")
    mix = sd.design(dur, events, orig, ambience=plan.get("ambience", "car interior"), unease=plan.get("unease", "low"), bumps=bool(plan.get("bumps", True)),
                    scare=float(plan.get("scare_at", -1) or -1), keep_original=True, seed=seed, flaws={"some": 0.45, "a lot": 0.9}.get(plan.get("flaws", "a lot"), 0.0), crowd=crowd_files,
                    bed_fade=tuple(fade) if fade else None)
    wav = out + ".wav"
    sd.write_wav(wav, mix)
    ramp = plan.get("ramp") or {}
    a, b, c = float(ramp.get("from_db", 4)), float(ramp.get("to_db", 13)), float(ramp.get("curve", 1.4))
    chain = sd.CHEAP_MIC if plan.get("cheap_mic", True) else "highpass=f=80,lowpass=f=10000,acompressor=threshold=0.08:ratio=2:attack=15:release=300,alimiter=limit=0.95"
    af = f"{chain},volume='pow(10,({a}+({b}-{a})*pow(clip(t/{max(0.5, total):.2f},0,1),{c}))/20)':eval=frame,alimiter=limit=0.95"
    try:
        _run(["-i", look, "-i", wav, "-map", "0:v:0", "-map", "1:a:0", "-c:v", "copy", "-af", af, "-c:a", "aac", "-b:a", "128k", "-shortest", "-movflags", "+faststart", out])
    finally:
        try:
            os.unlink(wav)
        except OSError:
            pass


API = "http://127.0.0.1:8000"


def synth_line(text: str, voice: str, exaggeration: float, out_wav: str, seed: int = 0) -> bool:
    """One narration line in the chosen voice (local Chatterbox via the app's own /api/tts routes) -> out_wav."""
    import httpx
    r = httpx.post(API + "/api/tts/speak", data={"text": text, "voice": voice, "exaggeration": exaggeration, "cfg_weight": 0.5, "seed": seed}, timeout=60)
    r.raise_for_status()
    jid = r.json()["job_id"]
    t0 = time.time()
    while time.time() - t0 < 420:
        a = httpx.get(f"{API}/api/tts/audio/{jid}", timeout=60)
        if a.status_code == 200 and len(a.content) > 2000:
            Path(out_wav).write_bytes(a.content)
            return True
        time.sleep(2)
    return False


def caption_png(text: str, style: str, W: int, path: str, avatar: str | None = None, header: str = "Reply to a comment") -> None:
    """A TikTok-style on-screen caption (white bold text on a black rounded box) or a generic 'reply to a comment' bubble. No brand logos or handles."""
