"""Chaos cut: the fast, chaotic, found-footage finish.

What makes a clip of a frightening event read as real is not any one effect but the *editing and the audio of panic*:
  short, getting shorter     every shot is trimmed to its useful moment, and the pace tightens toward the climax
  no model glitches          the video model sometimes invents a different scene in the last second of a clip; that tail is found and cut off
  the lines survive          each shot is trimmed AROUND the spoken line (found with speech recognition), never through it
  a camera that panics       the shake of the final pass follows each shot's chaos level, calm to frantic, with a short ramp at every cut
  a crowd                    other people talking, then shouting, then screaming over the main line (voice beds generated by the video model)
  human errors               a hand covering the microphone, scrapes, wind on the capsule, overload (see sounddesign.mic_flaws)
  a build                    the level rises across the whole video and peaks on the climax
  a clean take               several random mic-mishap placements are rendered and the one with no mid-build dips is kept

Routes:
  POST /api/tools/chaos_analyze   one clip  -> length, loudness, where the glitch tail starts, the spoken lines
  POST /api/tools/chaos_plan      analyses  -> an editable plan (trims, chaos, gains, crowd placement)
  POST /api/tools/chaos_cut       plan + clips + voice beds -> the finished mp4
"""
