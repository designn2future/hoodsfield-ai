    if style == "strip":     # a trail camera's black data bar along the bottom edge: moon, temperature, date and time
        mono = next((p for p in ("C:/Windows/Fonts/consola.ttf", "C:/Windows/Fonts/cour.ttf", "C:/Windows/Fonts/arial.ttf") if os.path.exists(p)), None)
        fs3 = max(11, int(W * 0.034))
        f3 = ImageFont.truetype(mono, fs3) if mono else ImageFont.load_default()
        im3 = Image.new("RGBA", (W, int(fs3 * 2.1)), (0, 0, 0, 235))
        ImageDraw.Draw(im3).text((10, int(fs3 * 0.5)), text, font=f3, fill=(255, 255, 255, 240))
        im3.save(path)
        return
    if style == "stamp":     # the timestamp / camera-name text a security or doorbell app burns into the corner
        mono = next((p for p in ("C:/Windows/Fonts/consola.ttf", "C:/Windows/Fonts/cour.ttf", "C:/Windows/Fonts/arial.ttf") if os.path.exists(p)), None)
        f2 = ImageFont.truetype(mono, max(12, int(W * 0.038))) if mono else ImageFont.load_default()
        tw2 = int(f2.getlength(text)) + 12
        th2 = int(max(12, int(W * 0.038)) * 1.5)
        im2 = Image.new("RGBA", (tw2, th2), (0, 0, 0, 0))
        ImageDraw.Draw(im2).text((6, 3), text, font=f2, fill=(255, 255, 255, 235), stroke_width=2, stroke_fill=(0, 0, 0, 190))
